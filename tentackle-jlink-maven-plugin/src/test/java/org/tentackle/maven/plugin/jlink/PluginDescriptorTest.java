package org.tentackle.maven.plugin.jlink;

import org.testng.SkipException;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.DataProvider;
import org.testng.annotations.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import java.net.URL;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertNotNull;

/**
 * Tests the plugin descriptor generated from the mojo annotations.
 * <p>
 * Goal names, lifecycle phases, dependency resolution scopes and the parameter defaults are the
 * plugin's API: every pom binding a goal depends on them, and the {@code @Mojo}/{@code @Parameter}
 * annotations are not retained at runtime. They are therefore asserted against
 * {@code META-INF/maven/plugin.xml}, which is what maven actually reads.
 * <p>
 * The descriptor is generated in the {@code process-classes} phase, hence it is available to the
 * tests of the very same build.
 */
@SuppressWarnings({ "exports", "missing-explicit-ctor" })
public class PluginDescriptorTest {

  private Map<String, Element> mojos;


  @BeforeClass
  public void setUp() throws Exception {
    URL url = getClass().getResource("/META-INF/maven/plugin.xml");
    if (url == null) {
      throw new SkipException("no plugin descriptor: run the tests as part of the maven build");
    }

    DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
    factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
    Document document = factory.newDocumentBuilder().parse(url.toString());

    List<Element> mojosElement = children(document.getDocumentElement(), "mojos");
    assertEquals(mojosElement.size(), 1, "malformed plugin descriptor");

    mojos = new HashMap<>();
    for (Element mojo : children(mojosElement.get(0), "mojo")) {
      mojos.put(text(mojo, "goal"), mojo);
    }
  }


  /**
   * The goals of this plugin.
   *
   * @return the goal name, implementation, phase, aggregator flag and resolution scope
   */
  @DataProvider(name = "goals")
  public Object[][] goals() {
    return new Object[][] {
      { "jlink", JLinkMojo.class, "package", "false", "runtime" },
      { "jpackage", JPackageMojo.class, "package", "false", "runtime" },
      { "init", InitMojo.class, null, "true", null }
    };
  }

  @Test(dataProvider = "goals")
  public void goalIsDeclaredAsExpected(String goal, Class<?> mojoClass, String phase,
                                       String aggregator, String scope) {
    Element mojo = mojo(goal);

    assertEquals(text(mojo, "implementation"), mojoClass.getName());
    assertEquals(text(mojo, "phase"), phase);
    assertEquals(text(mojo, "aggregator"), aggregator);
    assertEquals(text(mojo, "requiresDependencyResolution"), scope);
  }

  /**
   * Nothing but the goals above (and the generated help goal) is published.
   */
  @Test
  public void publishesExactlyTheDeclaredGoals() {
    List<String> declared = new ArrayList<>(mojos.keySet());
    declared.remove("help");    // generated by the maven-plugin-plugin

    List<String> expected = new ArrayList<>();
    for (Object[] goal : goals()) {
      expected.add((String) goal[0]);
    }

    declared.sort(null);
    expected.sort(null);
    assertEquals(declared, expected);
  }

  /**
   * Both image goals write to their own directory and share the template folder, so that a project
   * building both a zip and an installer can re-use the jlink image.
   */
  @Test
  public void theGoalsAgreeOnTheProjectLayout() {
    for (String goal : List.of("jlink", "jpackage")) {
      assertEquals(defaultValue(goal, "templateDir"), "${project.basedir}/templates", goal);
      assertEquals(defaultValue(goal, "imageDirectory"), "${project.build.directory}/jlink", goal);
      assertEquals(defaultValue(goal, "zipDirectory"), "${project.build.directory}", goal);
      assertEquals(defaultValue(goal, "resourcesDirectory"), "${project.build.directory}/classes", goal);
      assertEquals(defaultValue(goal, "finalName"), "${project.build.finalName}", goal);
    }

    assertEquals(defaultValue("jpackage", "packageDirectory"), "${project.build.directory}/jpackage");
  }

  /**
   * The template names default to the files the plugin ships, and the constants naming them must
   * agree with the descriptor.
   */
  @Test
  public void theTemplateNamesDefaultToTheShippedOnes() {
    assertEquals(defaultValue("jlink", "nameTemplate"), JLinkMojo.NAME_TEMPLATE);
    assertEquals(defaultValue("jlink", "runTemplate"), JLinkMojo.RUN_TEMPLATE);
    assertEquals(defaultValue("jlink", "updateTemplate"), JLinkMojo.UPDATE_TEMPLATE);
    assertEquals(defaultValue("jpackage", "packageImageTemplate"), JPackageMojo.PACKAGE_IMAGE_TEMPLATE);
    assertEquals(defaultValue("jpackage", "packageInstallerTemplate"), JPackageMojo.PACKAGE_INSTALLER_TEMPLATE);
    assertEquals(defaultValue("jpackage", "packageUpdateTemplate"), JPackageMojo.PACKAGE_UPDATE_TEMPLATE);
  }

  /**
   * The tools can be selected from the command line, which is the documented escape hatch for
   * builds that cannot use toolchains.
   */
  @Test
  public void theToolsAreConfigurableFromTheCommandLine() {
    assertEquals(expression("jlink", "jdepsTool"), "${jdepsTool}");
    assertEquals(expression("jlink", "jlinkTool"), "${jlinkTool}");
    assertEquals(expression("jpackage", "jpackageTool"), "${jpackageTool}");
  }

  /**
   * The main class is the only required parameter, and the precedence has a default.
   */
  @Test
  public void theRequiredParametersAreDeclared() {
    assertEquals(type("jlink", "mainClass"), "java.lang.String");
    assertEquals(required("jlink", "mainClass"), "true");
    assertEquals(required("jlink", "mainModule"), "false");
    assertEquals(defaultValue("jlink", "variablesPrecedence"), "system, maven, variables");
    assertEquals(required("jlink", "variablesPrecedence"), "true");
  }

  /**
   * The init goal only installs templates: it must not resolve dependencies for that.
   */
  @Test
  public void theInitGoalNeedsNoDependencies() {
    assertEquals(text(mojo("init"), "requiresDependencyResolution"), null);
    assertEquals(defaultValue("init", "copyAll"), "true");
  }


  private Element mojo(String goal) {
    Element mojo = mojos.get(goal);
    assertNotNull(mojo, "no such goal: " + goal + ", got " + mojos.keySet());
    return mojo;
  }

  /**
   * Gets the {@code default-value} of a parameter.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the default value, null if none
   */
  private String defaultValue(String goal, String parameter) {
    return attribute(configuration(goal, parameter), "default-value");
  }

  /**
   * Gets the expression a parameter is configurable by, i.e. its {@code property}.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the expression, null if none
   */
  private String expression(String goal, String parameter) {
    String expression = configuration(goal, parameter).getTextContent();
    return expression == null || expression.isEmpty() ? null : expression;
  }

  /**
   * Gets the declared type of a parameter.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the type name
   */
  private String type(String goal, String parameter) {
    return text(parameter(goal, parameter), "type");
  }

  /**
   * Gets whether a parameter is required.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return "true" or "false"
   */
  private String required(String goal, String parameter) {
    return text(parameter(goal, parameter), "required");
  }

  private Element parameter(String goal, String parameter) {
    for (Element element : children(parameters(goal), "parameter")) {
      if (parameter.equals(text(element, "name"))) {
        return element;
      }
    }
    throw new IllegalArgumentException(goal + " has no parameter " + parameter);
  }

  private Element parameters(String goal) {
    List<Element> parameters = children(mojo(goal), "parameters");
    assertEquals(parameters.size(), 1, goal + " has no parameters");
    return parameters.get(0);
  }

  private Element configuration(String goal, String parameter) {
    List<Element> configurations = children(mojo(goal), "configuration");
    assertEquals(configurations.size(), 1, goal + " has no configuration");
    List<Element> parameters = children(configurations.get(0), parameter);
    assertEquals(parameters.size(), 1, goal + " has no parameter " + parameter);
    return parameters.get(0);
  }

  private String attribute(Element element, String name) {
    return element.hasAttribute(name) ? element.getAttribute(name) : null;
  }

  private String text(Element parent, String name) {
    List<Element> elements = children(parent, name);
    return elements.isEmpty() ? null : elements.get(0).getTextContent();
  }

  private List<Element> children(Element parent, String name) {
    List<Element> elements = new ArrayList<>();
    NodeList nodes = parent.getChildNodes();
    for (int i = 0; i < nodes.getLength(); i++) {
      Node node = nodes.item(i);
      if (node instanceof Element element && element.getTagName().equals(name)) {
        elements.add(element);
      }
    }
    return elements;
  }

}

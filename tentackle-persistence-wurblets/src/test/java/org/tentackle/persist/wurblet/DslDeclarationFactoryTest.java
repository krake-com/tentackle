package org.tentackle.persist.wurblet;

import org.testng.annotations.BeforeClass;
import org.testng.annotations.Test;
import org.wurbelizer.wurbel.WurbelException;

import org.tentackle.model.Attribute;
import org.tentackle.model.Entity;
import org.tentackle.model.Model;
import org.tentackle.model.ModelException;
import org.tentackle.model.parse.Document;

import java.util.List;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertTrue;
import static org.testng.Assert.expectThrows;

/**
 * Tests the declarations generated by the QueryDSL wurblet.
 * <p>
 * The generator is a pure function of the model plus the wurblet options, so the test builds a real
 * {@link Entity} from the model-definition DSL and invokes the factory directly, without the
 * {@code Wurbler} container.
 *
 * @author harald
 */
public class DslDeclarationFactoryTest {

  /**
   * A model covering the cases the generator branches on: a primitive, a multi-column type,
   * a type with a variant (a String of size 0 is a large string) and a generic type.
   */
  private static final String TEST_MODEL = """
      name := Customer
      id := 1
      table := customer
      alias := cu

      String(30)     name        name        the customer name
      boolean        active      active      true if active
      long           visits      visits      the number of visits
      BMoney         turnover    turnover    the turnover
      String(0)      notes       notes       the notes
      Binary<String> attachment  attachment  the attachment
      """;

  private Entity entity;


  @BeforeClass
  public void createEntity() throws ModelException {
    entity = Model.getInstance().getEntityFactory().createEntity(new Document(TEST_MODEL), null);
  }

  /**
   * Creates the factory for the test entity.
   *
   * @return the factory
   * @throws WurbelException if the entity is not persistable
   */
  private DslDeclarationFactory createFactory() throws WurbelException {
    return new DslDeclarationFactory(entity);
  }

  /**
   * Generates the declaration of a single attribute.
   *
   * @param factory the factory
   * @param javaName the java name of the attribute
   * @return the generated code
   * @throws WurbelException if the attribute could not be generated
   */
  private String fieldCode(DslDeclarationFactory factory, String javaName) throws WurbelException {
    List<Attribute> attributes = factory.determineAttributes(List.of(javaName));
    return factory.createFieldDeclaration(attributes.getFirst()).code();
  }


  @Test
  public void testTableDeclaration() throws WurbelException {
    DslDeclarationFactory factory = createFactory();
    DslDeclarationFactory.Declaration declaration = factory.createTableDeclaration();

    assertEquals(declaration.code(), "private static final Table CUSTOMER = DSL.table(\"customer\", \"cu\");");
    assertEquals(declaration.comment(), "the query DSL table of entity Customer");

    // without an alias the columns are qualified with the table name
    factory.setTableAlias(null);
    assertEquals(factory.createTableDeclaration().code(),
                 "private static final Table CUSTOMER = DSL.table(\"customer\");");

    factory.setTableAlias("c");
    factory.setTableConstant("CUST");
    factory.setVisibility("public");
    assertEquals(factory.createTableDeclaration().code(),
                 "public static final Table CUST = DSL.table(\"customer\", \"c\");");
  }


  @Test
  public void testFieldDeclarations() throws WurbelException {
    DslDeclarationFactory factory = createFactory();

    // the column name comes from the model, not from the java name
    assertEquals(fieldCode(factory, "name"),
                 "private static final Field<String> NAME = CUSTOMER.field(\"name\", String.class);");

    // primitives become their wrapper, since the values of a query are objects
    assertEquals(fieldCode(factory, "active"),
                 "private static final Field<Boolean> ACTIVE = CUSTOMER.field(\"active\", Boolean.class);");
    assertEquals(fieldCode(factory, "visits"),
                 "private static final Field<Long> VISITS = CUSTOMER.field(\"visits\", Long.class);");

    // a multi-column datatype needs no special treatment: the DSL derives the columns from it
    assertEquals(fieldCode(factory, "turnover"),
                 "private static final Field<BMoney> TURNOVER = CUSTOMER.field(\"turnover\", BMoney.class);");

    // a variant cannot be determined from the class alone
    assertEquals(fieldCode(factory, "notes"),
                 "private static final Field<String> NOTES = " +
                 "CUSTOMER.field(\"notes\", DataTypeFactory.getInstance().get(String.class, \"LargeString\"));");

    // there is no class literal for a generic type
    assertEquals(fieldCode(factory, "attachment"),
                 "private static final Field<Object> ATTACHMENT = CUSTOMER.field(\"attachment\");");
  }


  @Test
  public void testVisibilityAndPrefix() throws WurbelException {
    DslDeclarationFactory factory = createFactory();
    factory.setVisibility("public");
    factory.setConstantPrefix(factory.getDefaultConstantPrefix());

    assertEquals(factory.getDefaultConstantPrefix(), "CUSTOMER_");
    assertEquals(fieldCode(factory, "name"),
                 "public static final Field<String> CUSTOMER_NAME = CUSTOMER.field(\"name\", String.class);");
  }


  @Test
  public void testAllAttributes() throws WurbelException {
    DslDeclarationFactory factory = createFactory();
    List<String> names = factory.determineAttributes(List.of()).stream().map(Attribute::getName).toList();

    // all attributes mapped by the entity, including the implicit ones
    assertTrue(names.containsAll(List.of("name", "active", "visits", "turnover", "notes", "attachment")),
               "missing attributes in " + names);
    assertTrue(names.contains("id"), "missing implicit attributes in " + names);
  }


  @Test
  public void testUnknownAttribute() throws WurbelException {
    DslDeclarationFactory factory = createFactory();
    WurbelException wex = expectThrows(WurbelException.class, () -> factory.determineAttributes(List.of("nosuch")));
    assertTrue(wex.getMessage().contains("no such attribute"), "unexpected message: " + wex.getMessage());
  }

}

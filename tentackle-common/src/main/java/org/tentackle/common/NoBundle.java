package org.tentackle.common;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Annotation to express that the annotated class looks like a bundle, but is not one.
 * <p>
 * The {@code bundles} goal of the tentackle-check-maven-plugin treats {@code getString} invocations on a
 * {@link java.util.ResourceBundle} referenced by a method or variable, such as {@code getBundle().getString("key")},
 * as lookups in the bundle named after the invoking class. If that class is not registered via {@link Bundle},
 * the goal reports an error. Annotating the class with {@code @NoBundle} excludes those invocations from the check.
 * <p>
 * Use it for classes that load an ordinary resource bundle which must not be registered via {@link Bundle},
 * because registered bundles are pushed to and pulled from the database by the tentackle-i18n-maven-plugin.
 * An example is the {@code Version} class generated by the tentackle-project-archetype, which reads the
 * build properties from a bundle of the same name.
 *
 * @author harald
 */
@Documented
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.TYPE)
public @interface NoBundle {
}

package org.tentackle.common;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Objects;
import java.util.Properties;
import java.util.Set;

/**
 * The declarative description of a whole {@link ModuleLayer} graph, as built by {@link ModuleLayerBuilder}
 * and consumed by {@link LayerBootstrap}.
 * <p>
 * Parsed from a flat {@code .properties} file, e.g., generated by the {@code tentackle-jlink-maven-plugin}.
 * The following example isolates two versions of the same library, each consumed by its own plugin layer.
 * The plugins' service interface lives in the boot layer, which all layers share:
 * <pre>
 * layer.lib-v1.dir=mp/lib-v1
 * layer.lib-v2.dir=mp/lib-v2
 * layer.plugin-a.parent=lib-v1
 * layer.plugin-a.dir=mp/plugin-a
 * layer.plugin-b.parent=lib-v2
 * layer.plugin-b.dir=mp/plugin-b
 * layer.app.dir=mp/app
 * leaf=app
 * leaf.mainModule=com.example.app
 * leaf.mainClass=com.example.app.Main
 * </pre>
 * Notice that a layer must not have two parents that define the same module, such as
 * {@code layer.app.parent=lib-v1,lib-v2} (see {@link ModuleLayerBuilder}).
 * <p>
 * Parsing rules:
 * <ul>
 * <li>A layer is declared by its {@code layer.<name>.dir} property, which is mandatory and may hold several
 * comma-separated directories.</li>
 * <li>{@code layer.<name>.parent} is optional. Missing or empty means the layer is parented on the boot layer.</li>
 * <li>{@code leaf} and {@code leaf.mainClass} are mandatory, {@code leaf.mainModule} is optional.</li>
 * <li>Relative directories are resolved against the base directory passed to {@link #parse(Properties, java.nio.file.Path)}.</li>
 * <li>The values are split via {@link StringHelper#split(String, String)}, which interprets backslashes as escape characters.
 * Hence, use forward slashes in paths, even on Windows.</li>
 * </ul>
 *
 * @param layers the layers, in no particular order (see {@link ModuleLayerBuilder} for the build order)
 * @param leafLayerName the name of the leaf layer, i.e., the layer holding the real application
 * @param leafMainModule the module holding the real application's main class, null or blank if not given.
 *                       If given, the module is added to the leaf layer's root modules and the package of the main
 *                       class is opened to tentackle-common, so that {@link LayerBootstrap} can invoke it.
 *                       Otherwise, the main class must be accessible without that.
 * @param leafMainClass the real application's main class
 *
 * @author harald
 */
public record LayerGraphSpec(List<LayerSpec> layers, String leafLayerName, String leafMainModule, String leafMainClass) {

  private static final String LAYER_PREFIX = "layer.";
  private static final String PARENT_SUFFIX = ".parent";
  private static final String DIR_SUFFIX = ".dir";
  private static final String LEAF_KEY = "leaf";
  private static final String LEAF_MAIN_MODULE_KEY = "leaf.mainModule";
  private static final String LEAF_MAIN_CLASS_KEY = "leaf.mainClass";

  /**
   * Creates a layer graph spec.
   *
   * @param layers the layers
   * @param leafLayerName the name of the leaf layer
   * @param leafMainModule the module holding the main class, null if not given
   * @param leafMainClass the main class
   * @throws NullPointerException if layers, leafLayerName or leafMainClass is null
   */
  public LayerGraphSpec {
    Objects.requireNonNull(layers, "layers");
    Objects.requireNonNull(leafLayerName, "leafLayerName");
    Objects.requireNonNull(leafMainClass, "leafMainClass");
    layers = List.copyOf(layers);
  }

  /**
   * Parses a layer graph specification from a properties file, resolving relative
   * directories against a base directory.
   *
   * @param props the properties
   * @param baseDir the directory relative directory entries are resolved against
   * @return the parsed spec
   * @throws TentackleRuntimeException if a layer has no directory, or the leaf layer or main class is missing
   */
  public static LayerGraphSpec parse(Properties props, java.nio.file.Path baseDir) {
    Objects.requireNonNull(props, "props");
    Objects.requireNonNull(baseDir, "baseDir");

    Set<String> names = new LinkedHashSet<>();
    for (String key : props.stringPropertyNames()) {
      if (key.startsWith(LAYER_PREFIX)) {
        if (key.endsWith(DIR_SUFFIX)) {
          names.add(key.substring(LAYER_PREFIX.length(), key.length() - DIR_SUFFIX.length()));
        }
        else if (key.endsWith(PARENT_SUFFIX)) {
          names.add(key.substring(LAYER_PREFIX.length(), key.length() - PARENT_SUFFIX.length()));
        }
      }
    }

    List<LayerSpec> layers = new ArrayList<>();
    for (String name : names) {
      List<String> parentNames = StringHelper.split(props.getProperty(LAYER_PREFIX + name + PARENT_SUFFIX, ""), ",")
              .stream().map(String::trim).filter(s -> !s.isEmpty()).toList();

      String dirValue = props.getProperty(LAYER_PREFIX + name + DIR_SUFFIX);
      if (dirValue == null || dirValue.isBlank()) {
        throw new TentackleRuntimeException("layer '" + name + "' has no directory configured");
      }
      List<java.nio.file.Path> directories = new ArrayList<>();
      for (String dir : StringHelper.split(dirValue, ",")) {
        directories.add(baseDir.resolve(dir.trim()));
      }

      layers.add(new LayerSpec(name, parentNames, directories));
    }

    String leaf = props.getProperty(LEAF_KEY);
    if (leaf == null || leaf.isBlank()) {
      throw new TentackleRuntimeException("no leaf layer configured (property '" + LEAF_KEY + "' missing)");
    }

    String leafMainClass = props.getProperty(LEAF_MAIN_CLASS_KEY);
    if (leafMainClass == null || leafMainClass.isBlank()) {
      throw new TentackleRuntimeException("no '" + LEAF_MAIN_CLASS_KEY + "' configured");
    }

    return new LayerGraphSpec(layers, leaf, props.getProperty(LEAF_MAIN_MODULE_KEY), leafMainClass);
  }

}

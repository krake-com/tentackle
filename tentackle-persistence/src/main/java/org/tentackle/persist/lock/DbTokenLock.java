  // @wurblet selectByPdoClassIdAndId DbSelectUnique --model=$mapfile pdoClassId id

  /**
   * Selects by pdoClassId and ID to implement {@link #reloadObject()} correctly,
   * if IDs are not unique among all PDO classes (which is NOT the default, but applications
   * could use different IdSources / Sequences for PDO classes).
   *
   * @param pdoClassId the PDO's class ID
   * @param id the PDO's ID
   * @return the token lock, null if not found
   */
  //<editor-fold defaultstate="collapsed" desc="code 'selectByPdoClassIdAndId' generated by wurblet DbSelectUnique">//GEN-BEGIN:selectByPdoClassIdAndId

  public DbTokenLock selectByPdoClassIdAndId(int pdoClassId, long id) {
    PreparedStatementWrapper st = getPreparedStatement(SELECT_BY_PDO_CLASS_ID_AND_ID_STMT,
      b -> {
        StringBuilder sql = createSelectAllInnerSql(b);
        sql.append(Backend.SQL_AND);
        sql.append(CN_PDOCLASSID);
        sql.append(Backend.SQL_EQUAL_PAR);
        sql.append(Backend.SQL_AND);
        sql.append(CN_ID);
        sql.append(Backend.SQL_EQUAL_PAR);
        b.buildSelectSql(sql, false, 0, 0);
        return sql.toString();
      }
    );
    int ndx = 1;
    st.setInt(ndx++, pdoClassId);
    st.setLong(ndx, id);
    try (ResultSetWrapper rs = st.executeQuery()) {
      if (rs.next()) {
        return readFromResultSetWrapper(rs);
      }
      return null;  // not found
    }
  }

  private static final StatementId SELECT_BY_PDO_CLASS_ID_AND_ID_STMT = new StatementId();


  //</editor-fold>//GEN-END:selectByPdoClassIdAndId

  /**
   * {@inheritDoc}
   * <p>
   * Overridden to select by PDO class ID and ID, since the ID alone is not unique.
   */
  @Override
  public DbTokenLock reloadObject() {
    // select by pdoclassid + id!
    return newInstance().selectByPdoClassIdAndId(pdoClassId, getId());
  }

  /**
   * {@inheritDoc}
   * <p>
   * Overridden to update by PDO class ID, ID and serial, since the ID alone is not unique.
   */
  @Override
  public String createUpdateSql(Backend backend) {
    // method not generated by MethodsImpl due to [NOPKEY] option.
    // update by pdoclassid + id + serial!
    return Backend.SQL_UPDATE + getTableName() + Backend.SQL_SET +
           CN_LOCKEDBY + Backend.SQL_EQUAL_PAR_COMMA +
           CN_LOCKEDSINCE + Backend.SQL_EQUAL_PAR_COMMA +
           CN_LOCKEXPIRY + Backend.SQL_EQUAL_PAR_COMMA +
           CN_SERIAL + Backend.SQL_EQUAL + CN_SERIAL + Backend.SQL_PLUS_ONE +
           Backend.SQL_WHERE + CN_PDOCLASSID + Backend.SQL_EQUAL_PAR +
           Backend.SQL_AND + CN_ID + Backend.SQL_EQUAL_PAR +
           Backend.SQL_AND + CN_SERIAL + Backend.SQL_EQUAL_PAR;
  }

  /**
   * {@inheritDoc}
   * <p>
   * Overridden to delete by PDO class ID, ID and serial, since the ID alone is not unique.
   */
  @Override
  public String createDeleteSql(Backend backend) {
    // delete by pdoclassid + id + serial!
    return SQL_DELETE_FROM + getTableName() + SQL_WHERE +
           CN_PDOCLASSID + SQL_EQUAL_PAR + SQL_AND +
           CN_ID + SQL_EQUAL_PAR + SQL_AND +
           CN_SERIAL + SQL_EQUAL_PAR;
  }

  /**
   * {@inheritDoc}
   * <p>
   * Overridden to bind the PDO class ID, ID and serial.
   */
  @Override
  protected void deleteImpl(DbObjectClassVariables<DbTokenLock> classVariables, SqlSupplier sqlSupplier) {
    // delete by pdoclassid + id + serial!
    PreparedStatementWrapper st = getPreparedStatement(classVariables.deleteStatementId, sqlSupplier);
    st.setInt(1, pdoClassId);
    st.setLong(2, getId());
    st.setLong(3, getSerial());
    assertThisRowAffected(st.executeUpdate());
  }


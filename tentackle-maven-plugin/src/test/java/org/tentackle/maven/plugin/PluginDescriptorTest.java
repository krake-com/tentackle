package org.tentackle.maven.plugin;

import org.testng.SkipException;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.DataProvider;
import org.testng.annotations.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import java.net.URL;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertNotNull;

/**
 * Tests the plugin descriptor generated from the mojo annotations.
 * <p>
 * Goal names, lifecycle phases, dependency resolution scopes and the user properties of the
 * parameters are the plugin's API: every pom binding a goal depends on them, and the
 * {@code @Mojo}/{@code @Parameter} annotations are not retained at runtime. They are therefore
 * asserted against {@code META-INF/maven/plugin.xml}, which is what maven actually reads.
 * <p>
 * The descriptor is generated in the {@code process-classes} phase, hence it is available to
 * the tests of the very same build.
 */
@SuppressWarnings("missing-explicit-ctor")
public class PluginDescriptorTest {

  private Map<String, Element> mojos;


  @BeforeClass
  public void setUp() throws Exception {
    URL url = getClass().getResource("/META-INF/maven/plugin.xml");
    if (url == null) {
      throw new SkipException("no plugin descriptor: run the tests as part of the maven build");
    }

    DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
    factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
    Document document = factory.newDocumentBuilder().parse(url.toString());

    List<Element> mojosElement = children(document.getDocumentElement(), "mojos");
    assertEquals(mojosElement.size(), 1, "malformed plugin descriptor");

    mojos = new HashMap<>();
    for (Element mojo : children(mojosElement.get(0), "mojo")) {
      mojos.put(text(mojo, "goal"), mojo);
    }
  }


  /**
   * The goals of this plugin.
   *
   * @return the goal name, implementation, phase, aggregator flag and resolution scope
   */
  @DataProvider(name = "goals")
  public Object[][] goals() {
    return new Object[][] {
      { "analyze", AnalyzeAnnotationProcessingMojo.class, "generate-sources", "false", "compile" },
      { "test-analyze", AnalyzeTestAnnotationProcessingMojo.class, "generate-test-sources", "false", "test" },
      { "beaninfo", BeanInfoMojo.class, "generate-resources", "false", "compile" },
      { "properties", PropertiesMojo.class, "generate-resources", "false", "compile" },
      { "versions", VersionInfoMojo.class, "validate", "true", "compile" },
      { "plugin-versions", PluginVersionInfoMojo.class, "validate", "true", null }
    };
  }

  @Test(dataProvider = "goals")
  public void goalIsDeclaredAsExpected(String goal, Class<?> mojoClass, String phase,
                                       String aggregator, String scope) {
    Element mojo = mojo(goal);

    assertEquals(text(mojo, "implementation"), mojoClass.getName());
    assertEquals(text(mojo, "phase"), phase);
    assertEquals(text(mojo, "aggregator"), aggregator);
    assertEquals(text(mojo, "requiresDependencyResolution"), scope);
    assertEquals(text(mojo, "threadSafe"), "true", "goal " + goal + " is not thread-safe");
  }

  /**
   * Nothing but the goals above (and the generated help goal) is published.
   */
  @Test
  public void publishesExactlyTheDeclaredGoals() {
    List<String> declared = new ArrayList<>(mojos.keySet());
    declared.remove("help");    // generated by the maven-plugin-plugin

    List<String> expected = new ArrayList<>();
    for (Object[] goal : goals()) {
      expected.add((String) goal[0]);
    }

    declared.sort(null);
    expected.sort(null);
    assertEquals(declared, expected);
  }

  /**
   * Both analyze goals must write to their own directories, or the test sources would
   * overwrite the analyze results of the main sources.
   */
  @Test
  public void bothAnalyzeGoalsUseTheirOwnDirectories() {
    assertEquals(defaultValue("analyze", "sourceDir"), "${project.build.sourceDirectory}");
    assertEquals(defaultValue("analyze", "analyzeDir"), "${project.build.directory}/analyze");
    assertEquals(defaultValue("analyze", "servicesDir"), "${project.build.directory}/generated-resources/services");
    assertEquals(defaultValue("analyze", "classpathElements"), "${project.compileClasspathElements}");

    assertEquals(defaultValue("test-analyze", "sourceDir"), "${project.build.testSourceDirectory}");
    assertEquals(defaultValue("test-analyze", "analyzeDir"), "${project.build.directory}/test-analyze");
    assertEquals(defaultValue("test-analyze", "servicesDir"),
                 "${project.build.directory}/generated-test-resources/services");
    assertEquals(defaultValue("test-analyze", "classpathElements"), "${project.testClasspathElements}");
  }

  /**
   * The source- and analyze directories are shared with the wurbelizer plugin, which picks up
   * the analyze results. Configuring one of them must configure both.
   */
  @Test
  public void analyzeGoalsShareTheirDirectoriesWithTheWurbelizer() {
    assertEquals(expression("analyze", "sourceDir"), "${wurbel.sourceDir}");
    assertEquals(expression("analyze", "analyzeDir"), "${wurbel.analyzeDir}");
    assertEquals(expression("analyze", "servicesDir"), "${tentackle.serviceDir}");

    assertEquals(expression("test-analyze", "sourceDir"), "${wurbel.testSourceDir}");
    assertEquals(expression("test-analyze", "analyzeDir"), "${wurbel.testAnalyzeDir}");
    assertEquals(expression("test-analyze", "servicesDir"), "${tentackle.testServiceDir}");
  }

  /**
   * The beaninfo goal reads the sources of the project and writes a manifest fragment.
   */
  @Test
  public void beanInfoGoalUsesTheProjectSources() {
    assertEquals(defaultValue("beaninfo", "sourceDir"), "${project.build.sourceDirectory}");
    assertEquals(expression("beaninfo", "sourceDir"), "${tentackle.sourceDir}");
    assertEquals(defaultValue("beaninfo", "manifestDirectory"), "${project.build.directory}/generated-resources/manifest");
    assertEquals(expression("beaninfo", "manifestDirectory"), "${tentackle.manifestDirectory}");
  }

  /**
   * Both version goals can be invoked from the command line with the documented properties.
   */
  @Test
  public void versionGoalsAreConfigurableFromTheCommandLine() {
    assertEquals(expression("versions", "scope"), "${scope}");
    assertEquals(expression("versions", "outputFile"), "${outputFile}");
    assertEquals(expression("versions", "groupVersions"), "${groupVersions}");
    assertEquals(expression("plugin-versions", "outputFile"), "${outputFile}");
    assertEquals(expression("plugin-versions", "groupVersions"), "${groupVersions}");
  }


  private Element mojo(String goal) {
    Element mojo = mojos.get(goal);
    assertNotNull(mojo, "no such goal: " + goal + ", got " + mojos.keySet());
    return mojo;
  }

  /**
   * Gets the {@code default-value} of a parameter.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the default value, null if none
   */
  private String defaultValue(String goal, String parameter) {
    return attribute(configuration(goal, parameter), "default-value");
  }

  /**
   * Gets the expression a parameter is configurable by, i.e. its {@code property}.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the expression, null if none
   */
  private String expression(String goal, String parameter) {
    String expression = configuration(goal, parameter).getTextContent();
    return expression == null || expression.isEmpty() ? null : expression;
  }

  private Element configuration(String goal, String parameter) {
    List<Element> configurations = children(mojo(goal), "configuration");
    assertEquals(configurations.size(), 1, goal + " has no configuration");
    List<Element> parameters = children(configurations.get(0), parameter);
    assertEquals(parameters.size(), 1, goal + " has no parameter " + parameter);
    return parameters.get(0);
  }

  private String attribute(Element element, String name) {
    return element.hasAttribute(name) ? element.getAttribute(name) : null;
  }

  private String text(Element parent, String name) {
    List<Element> elements = children(parent, name);
    return elements.isEmpty() ? null : elements.get(0).getTextContent();
  }

  private List<Element> children(Element parent, String name) {
    List<Element> elements = new ArrayList<>();
    NodeList nodes = parent.getChildNodes();
    for (int i = 0; i < nodes.getLength(); i++) {
      Node node = nodes.item(i);
      if (node instanceof Element element && element.getTagName().equals(name)) {
        elements.add(element);
      }
    }
    return elements;
  }

}

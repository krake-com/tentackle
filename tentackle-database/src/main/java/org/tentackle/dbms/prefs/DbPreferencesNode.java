  /**
   * Gets the basename of the node.
   *
   * @return the node's basename
   */
  public String getBaseName() {
    int lastSlash = name.lastIndexOf('/');
    return lastSlash >= 0 ? name.substring(lastSlash + 1) : name;
  }



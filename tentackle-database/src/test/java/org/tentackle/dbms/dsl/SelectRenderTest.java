package org.tentackle.dbms.dsl;

import org.testng.annotations.Test;

import org.tentackle.common.BMoney;
import org.tentackle.session.PersistenceException;
import org.tentackle.sql.Backend;
import org.tentackle.sql.BackendFactory;

import java.util.List;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertTrue;
import static org.testng.Assert.expectThrows;

/**
 * Tests the SQL-code and the parameters generated by the query DSL.
 * <p>
 * Runs without a database, since rendering only needs a {@link Backend}.
 *
 * @author harald
 */
public class SelectRenderTest {

  private static final Backend BACKEND = BackendFactory.getInstance().getBackendByName("PostgreSQL");

  private static final Table POOL = DSL.table("numberpool", "np");
  private static final Field<Long> ID = POOL.field("id", Long.class);
  private static final Field<String> NAME = POOL.field("name", String.class);
  private static final Field<String> REALM = POOL.field("realm", String.class);
  private static final Field<BMoney> AMOUNT = POOL.field("amount", BMoney.class);

  private static final Table LOG = DSL.table("numberlog", "nl");
  private static final Field<Long> LOG_POOL_ID = LOG.field("poolid", Long.class);
  private static final Field<String> LOG_TEXT = LOG.field("text", String.class);

  private static final BMoney MONEY = new BMoney(17.11, 2);


  /**
   * Renders a select and verifies the SQL-code and the parameters.
   *
   * @param select the select
   * @param expectedSql the expected SQL-code
   * @param expectedParameters the expected parameters
   */
  private void assertRendered(Select select, String expectedSql, Object... expectedParameters) {
    RenderContext context = new RenderContext(BACKEND);
    select.render(context);
    assertEquals(context.getSql(), expectedSql);
    assertEquals(context.getParameters(), List.of(expectedParameters));
  }


  @Test
  public void testProjection() {
    assertRendered(DSL.select().from(POOL),
                   "SELECT * FROM numberpool np");

    assertRendered(DSL.select(POOL.asterisk()).from(POOL),
                   "SELECT np.* FROM numberpool np");

    assertRendered(DSL.selectDistinct(NAME, REALM).from(POOL),
                   "SELECT DISTINCT np.name, np.realm FROM numberpool np");

    // a multi-column datatype is expanded to all its columns
    assertRendered(DSL.select(NAME, AMOUNT).from(POOL),
                   "SELECT np.name, np.amount, np.amount_2 FROM numberpool np");

    // ... and so is its alias, so that the labels match the members of the DTO
    assertRendered(DSL.select(NAME.as("poolname"), AMOUNT.as("total")).from(POOL),
                   "SELECT np.name AS poolname, np.amount AS total, np.amount_2 AS total_2 FROM numberpool np");
  }


  @Test
  public void testConditions() {
    assertRendered(DSL.select(ID).from(POOL).where(NAME.eq("pool1")),
                   "SELECT np.id FROM numberpool np WHERE np.name=?", "pool1");

    // conditions of a select are combined by a logical AND
    assertRendered(DSL.select(ID).from(POOL).where(NAME.eq("pool1")).where(ID.gt(5L)),
                   "SELECT np.id FROM numberpool np WHERE np.name=? AND np.id>?", "pool1", 5L);

    assertRendered(DSL.select(ID).from(POOL).where(NAME.eq("pool1").or(NAME.eq("pool2"))),
                   "SELECT np.id FROM numberpool np WHERE (np.name=? OR np.name=?)", "pool1", "pool2");

    // ORs are flattened, ANDs are nested according to the parentheses
    assertRendered(DSL.select(ID).from(POOL).where(
                       NAME.eq("a").or(NAME.eq("b")).or(NAME.eq("c")).and(ID.le(7L))),
                   "SELECT np.id FROM numberpool np WHERE ((np.name=? OR np.name=? OR np.name=?) AND np.id<=?)",
                   "a", "b", "c", 7L);

    assertRendered(DSL.select(ID).from(POOL).where(NAME.like("pool%").not()),
                   "SELECT np.id FROM numberpool np WHERE NOT (np.name LIKE ?)", "pool%");

    assertRendered(DSL.select(ID).from(POOL).where(NAME.in(List.of("a", "b"))),
                   "SELECT np.id FROM numberpool np WHERE np.name IN (?, ?)", "a", "b");

    assertRendered(DSL.select(ID).from(POOL).where(ID.between(1L, 10L)),
                   "SELECT np.id FROM numberpool np WHERE np.id BETWEEN ? AND ?", 1L, 10L);

    assertRendered(DSL.select(ID).from(POOL).where(NAME.isNull(), REALM.isNotNull()),
                   "SELECT np.id FROM numberpool np WHERE np.name IS NULL AND np.realm IS NOT NULL");

    // an empty value set matches nothing at all
    assertRendered(DSL.select(ID).from(POOL).where(NAME.in(List.of())),
                   "SELECT np.id FROM numberpool np WHERE 1=0");

    assertRendered(DSL.select(ID).from(POOL).where(NAME.notIn(List.of())),
                   "SELECT np.id FROM numberpool np WHERE 1=1");
  }


  @Test
  public void testMultiColumnDataType() {
    // all columns must be equal, and the value is applied to as many question marks as columns
    assertRendered(DSL.select(ID).from(POOL).where(AMOUNT.eq(MONEY)),
                   "SELECT np.id FROM numberpool np WHERE (np.amount=? AND np.amount_2=?)", MONEY);

    assertRendered(DSL.select(ID).from(POOL).where(AMOUNT.ne(MONEY)),
                   "SELECT np.id FROM numberpool np WHERE NOT (np.amount=? AND np.amount_2=?)", MONEY);

    // a value spanning more than one column is null if all of its columns are null
    assertRendered(DSL.select(ID).from(POOL).where(AMOUNT.isNull()),
                   "SELECT np.id FROM numberpool np WHERE (np.amount IS NULL AND np.amount_2 IS NULL)");

    assertRendered(DSL.select(ID).from(POOL).where(AMOUNT.isNotNull()),
                   "SELECT np.id FROM numberpool np WHERE NOT (np.amount IS NULL AND np.amount_2 IS NULL)");

    // sorted by the sortable columns of the datatype only
    assertRendered(DSL.select(ID).from(POOL).orderBy(AMOUNT.desc()),
                   "SELECT np.id FROM numberpool np ORDER BY np.amount DESC");

    // ... but grouped by all of them
    assertRendered(DSL.select(AMOUNT).from(POOL).groupBy(AMOUNT),
                   "SELECT np.amount, np.amount_2 FROM numberpool np GROUP BY np.amount, np.amount_2");

    // relational operators cannot be applied column by column
    PersistenceException pex = expectThrows(PersistenceException.class,
        () -> DSL.select(ID).from(POOL).where(AMOUNT.gt(MONEY)).toSql(BACKEND));
    assertTrue(pex.getMessage().contains("not applicable"), "unexpected message: " + pex.getMessage());
  }


  @Test
  public void testFunctionsAndGrouping() {
    assertRendered(DSL.select(REALM, DSL.count().as("pools"))
                      .from(POOL)
                      .groupBy(REALM)
                      .having(DSL.count().gt(2L))
                      .orderBy(REALM.asc()),
                   "SELECT np.realm, COUNT(*) AS pools FROM numberpool np " +
                   "GROUP BY np.realm HAVING COUNT(*)>? ORDER BY np.realm ASC", 2L);

    assertRendered(DSL.select(DSL.countDistinct(REALM), DSL.avg(ID), DSL.max(NAME), DSL.upper(NAME)).from(POOL),
                   "SELECT COUNT(DISTINCT np.realm), AVG(np.id), MAX(np.name), UPPER(np.name) FROM numberpool np");

    // the backend decides whether it is COALESCE or NVL
    assertRendered(DSL.select(DSL.coalesce(NAME, DSL.value("unknown"))).from(POOL),
                   "SELECT COALESCE(np.name, ?) FROM numberpool np", "unknown");
  }


  @Test
  public void testJoins() {
    assertRendered(DSL.select(NAME, LOG_TEXT)
                      .from(POOL)
                      .leftJoin(LOG).on(LOG_POOL_ID.eq(ID))
                      .where(NAME.eq("pool1")),
                   "SELECT np.name, nl.text FROM numberpool np LEFT JOIN numberlog nl ON nl.poolid=np.id " +
                   "WHERE np.name=?", "pool1");

    // the parameters of the join condition are applied before those of the where-clause
    assertRendered(DSL.select(NAME)
                      .from(POOL)
                      .join(LOG).on(LOG_POOL_ID.eq(ID).and(LOG_TEXT.like("err%")))
                      .where(NAME.eq("pool1")),
                   "SELECT np.name FROM numberpool np JOIN numberlog nl ON (nl.poolid=np.id AND nl.text LIKE ?) " +
                   "WHERE np.name=?", "err%", "pool1");
  }


  @Test
  public void testSubSelects() {
    Select poolIds = DSL.select(LOG_POOL_ID).from(LOG).where(LOG_TEXT.like("err%"));

    assertRendered(DSL.select(NAME).from(POOL).where(ID.in(poolIds)),
                   "SELECT np.name FROM numberpool np WHERE np.id IN " +
                   "(SELECT nl.poolid FROM numberlog nl WHERE nl.text LIKE ?)", "err%");

    assertRendered(DSL.select(NAME).from(POOL).where(DSL.exists(
                       DSL.select(LOG_POOL_ID).from(LOG).where(LOG_POOL_ID.eq(ID)))),
                   "SELECT np.name FROM numberpool np WHERE EXISTS " +
                   "(SELECT nl.poolid FROM numberlog nl WHERE nl.poolid=np.id)");

    // a derived table
    Table derived = DSL.table(DSL.select(NAME, REALM).from(POOL).where(REALM.eq("r1")), "d");
    assertRendered(DSL.select(derived.field("name", String.class)).from(derived),
                   "SELECT d.name FROM (SELECT np.name, np.realm FROM numberpool np WHERE np.realm=?) d", "r1");
  }


  @Test
  public void testLimitAndOffset() {
    // the LIMIT- and OFFSET-clauses are backend-specific and thus added by the backend
    Select select = DSL.select(NAME).from(POOL).limit(10).offset(20);
    assertEquals(select.toSql(BACKEND), "SELECT np.name FROM numberpool np");
    assertEquals(select.toQuery(BACKEND).createSql(BACKEND).toString(),
                 "SELECT np.name FROM numberpool np LIMIT ? OFFSET ?");

    // ... which is not applicable to a sub-select
    PersistenceException pex = expectThrows(PersistenceException.class,
        () -> DSL.select(ID).from(POOL).where(ID.in(select)).toSql(BACKEND));
    assertTrue(pex.getMessage().contains("sub-select"), "unexpected message: " + pex.getMessage());
  }


  @Test
  public void testRawSql() {
    assertRendered(DSL.select(NAME, DSL.sql("np.id * 2", Long.class).as("doubled"))
                      .from(POOL)
                      .where(DSL.condition("np.realm = ?", "r1")),
                   "SELECT np.name, np.id * 2 AS doubled FROM numberpool np WHERE np.realm = ?", "r1");
  }


  @Test
  public void testIllegalNames() {
    // names end up in the SQL-code verbatim and thus are verified
    expectThrows(PersistenceException.class, () -> DSL.table("customer; DROP TABLE customer"));
    expectThrows(PersistenceException.class, () -> POOL.field("name = 1"));
    expectThrows(PersistenceException.class, () -> NAME.as("x y"));

    // schema-qualified names are fine
    assertEquals(DSL.select(NAME).from(DSL.table("public.numberpool", "np")).toSql(BACKEND),
                 "SELECT np.name FROM public.numberpool np");
  }


  @Test
  public void testNullValueRejected() {
    expectThrows(NullPointerException.class, () -> NAME.eq((String) null));
  }

}

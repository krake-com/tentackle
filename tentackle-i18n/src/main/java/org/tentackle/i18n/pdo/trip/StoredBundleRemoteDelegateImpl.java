package org.tentackle.i18n.pdo.trip;

import org.tentackle.i18n.pdo.StoredBundle;
import org.tentackle.i18n.pdo.StoredBundlePersistenceImpl;
import org.tentackle.dbms.trip.RemoteDbSessionImpl;
import org.tentackle.misc.TrackedList;
import org.tentackle.pdo.DomainContext;
import org.tentackle.persist.trip.AbstractPersistentObjectRemoteDelegateImpl;


/**
 * Remote delegate implementation for {@link StoredBundlePersistenceImpl}.
 */
public class StoredBundleRemoteDelegateImpl
       extends AbstractPersistentObjectRemoteDelegateImpl<StoredBundle,StoredBundlePersistenceImpl>
       implements StoredBundleRemoteDelegate {


  /**
   * Creates the remote delegate for {@link StoredBundlePersistenceImpl}.
   *
   * @param session the TRIP session
   * @param persistenceClass the persistence implementation class
   * @param pdoClass the pdo interface class
   */
  public StoredBundleRemoteDelegateImpl(RemoteDbSessionImpl session,
                                        Class<StoredBundlePersistenceImpl> persistenceClass,
                                        Class<StoredBundle> pdoClass) {
    super(session, persistenceClass, pdoClass);
  }

  // @wurblet inclrmi Include --missingok .$classname/methods

  //<editor-fold defaultstate="collapsed" desc="code 'inclrmi' generated by wurblet Include">//GEN-BEGIN:inclrmi


  @Override
  public StoredBundle selectByUniqueDomainKey(DomainContext context, String name, String locale) {
    return newInstance(context).selectByUniqueDomainKey(name, locale);
  }

  @Override
  public StoredBundle selectByUniqueDomainKeyForCache(DomainContext context, StoredBundle.StoredBundleUDK udk) {
    return newInstance(context).selectCachedByUniqueDomainKey(udk);
  }

  @Override
  public TrackedList<StoredBundle> findByName(DomainContext context, String name) {
    setDomainContext(context);
    return dbObject.findByName(name);
  }

  @Override
  public StoredBundle findByNameAndLocale(DomainContext context, String name, String locale) {
    return newInstance(context).findByNameAndLocale(name, locale);
  }

  //</editor-fold>//GEN-END:inclrmi

}

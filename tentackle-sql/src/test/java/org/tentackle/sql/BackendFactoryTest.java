package org.tentackle.sql;

import org.tentackle.common.EncryptedProperties;
import org.tentackle.sql.backends.H2;
import org.tentackle.sql.backends.Oracle;
import org.tentackle.sql.backends.Oracle21;
import org.tentackle.sql.backends.Oracle8;
import org.testng.annotations.Test;

import java.util.Collection;
import java.util.List;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertFalse;
import static org.testng.Assert.assertNotNull;
import static org.testng.Assert.assertSame;
import static org.testng.Assert.assertTrue;
import static org.testng.Assert.expectThrows;

/**
 * Tests {@link DefaultBackendFactory} and {@link DefaultBackendInfoFactory}.
 * <p>
 * The factory collects the backends via the SPI, so the test doubles as a check that the service
 * index generated by the build really lists all of them. The evaluation order matters: {@code Oracle}
 * and the deprecated {@code Oracle8} both match the same URL, and only the sorting by name makes the
 * non-deprecated one win.
 *
 * @author harald
 */
@SuppressWarnings("missing-explicit-ctor")
public class BackendFactoryTest {

  private final BackendFactory factory = BackendFactory.getInstance();


  @Test
  public void testSingleton() {
    assertSame(BackendFactory.getInstance(), factory);
    assertTrue(factory instanceof DefaultBackendFactory);
  }

  @Test
  public void testGetBackendByUrl() {
    assertEquals(factory.getBackendByUrl("jdbc:h2:mem:test").getName(), "H2");
    assertEquals(factory.getBackendByUrl("jdbc:postgresql://localhost/tentackle").getName(), "PostgreSQL");
    assertEquals(factory.getBackendByUrl("jdbc:mysql://localhost/tentackle").getName(), "MySQL");
    assertEquals(factory.getBackendByUrl("jdbc:mariadb://localhost/tentackle").getName(), "MariaDB");
    assertEquals(factory.getBackendByUrl("jdbc:sqlserver://localhost").getName(), "MsSQL");
    assertEquals(factory.getBackendByUrl("jdbc:db2://localhost/tentackle").getName(), "DB2");
    assertEquals(factory.getBackendByUrl("jdbc:informix-sqli://localhost/tentackle").getName(), "Informix");
    assertEquals(factory.getBackendByUrl("jdbc:sap://localhost:30015").getName(), "HANA");
    assertEquals(factory.getBackendByUrl("jdbc:firebirdsql://localhost/tentackle").getName(), "Firebird");
    assertEquals(factory.getBackendByUrl("jdbc:firebird://localhost/tentackle").getName(), "Firebird");
  }

  /**
   * CockroachDB is reached via the postgres driver, so its URL must still select postgres,
   * and CockroachDB only by name.
   */
  @Test
  public void testCockroachDbIsSelectedByNameOnly() {
    String url = "jdbc:postgresql://localhost:26257/tentackle";
    assertEquals(factory.getBackendByUrl(url).getName(), "PostgreSQL");
    BackendInfo info = BackendInfoFactory.getInstance().create(url + "|CockroachDB", "root", new char[0], null);
    assertEquals(info.getBackend().getName(), "CockroachDB");
    assertEquals(info.getUrl(), url);
  }

  /**
   * Both oracle backends accept the same URL, so the deprecated one must not shadow its successor.
   */
  @Test
  public void testOracleUrlPrefersTheCurrentBackend() {
    assertEquals(factory.getBackendByUrl("jdbc:oracle:thin:@localhost:1521:tentackle").getName(),
                 new Oracle().getName());
  }

  /**
   * {@code Oracle21} opts in to the native JSON type, but matches the very same URL as {@code Oracle}
   * and must therefore be selected by name only.
   */
  @Test
  public void testOracle21IsSelectedByNameOnly() {
    String url = "jdbc:oracle:thin:@localhost:1521:tentackle";
    assertEquals(factory.getBackendByUrl(url).getName(), new Oracle().getName());
    BackendInfo info = BackendInfoFactory.getInstance().create(url + "|Oracle21", "scott", new char[0], null);
    assertEquals(info.getBackend().getName(), new Oracle21().getName());
    assertEquals(info.getUrl(), url);
  }

  @Test
  public void testGetBackendByUnknownUrl() {
    assertTrue(expectThrows(BackendException.class, () -> factory.getBackendByUrl("jdbc:nosuchdb:x"))
                   .getMessage().contains("jdbc:nosuchdb:x"));
  }

  @Test
  public void testGetBackendByName() {
    assertEquals(factory.getBackendByName("H2").getName(), "H2");
    assertEquals(factory.getBackendByName("h2").getName(), "H2", "the name must match case-insensitively");
    assertEquals(factory.getBackendByName("Oracle8").getName(), "Oracle8", "deprecated backends are still nameable");
  }

  @Test
  public void testGetBackendByUnknownName() {
    assertTrue(expectThrows(BackendException.class, () -> factory.getBackendByName("nosuchbackend"))
                   .getMessage().contains("nosuchbackend"));
  }

  /**
   * The backends are singletons and the same instance must come back regardless of how it was looked up.
   */
  @Test
  public void testBackendsAreSingletons() {
    assertSame(factory.getBackendByName("H2"), factory.getBackendByUrl("jdbc:h2:mem:test"));
  }

  @Test
  public void testGetAllBackends() {
    Collection<Backend> all = factory.getAllBackends();
    assertTrue(names(all).contains(new H2().getName()));
    assertFalse(names(all).contains(new Oracle8().getName()), "deprecated backends must be omitted");
    assertEquals(names(all), names(all).stream().sorted().toList(), "must be sorted by name");
  }


  // ---- getBackends(String) -------------------------------------------------

  @Test
  public void testGetBackendsByName() {
    assertEquals(names(factory.getBackends("H2")), List.of("H2"));
    assertEquals(names(factory.getBackends("PostgreSQL, H2")), List.of("H2", "PostgreSQL"), "sorted by name");
    assertEquals(names(factory.getBackends("H2,H2")), List.of("H2"), "each backend only once");
  }

  @Test
  public void testGetBackendsSpecialNames() {
    assertEquals(names(factory.getBackends("all")), names(factory.getAllBackends()));
    assertEquals(names(factory.getBackends("ALL")), names(factory.getAllBackends()), "case-insensitive");
    assertEquals(names(factory.getBackends("deprecated")), List.of(new Oracle8().getName()));
    assertTrue(factory.getBackends("none").isEmpty());
    assertEquals(names(factory.getBackends("all,deprecated")).size(),
                 factory.getAllBackends().size() + 1, "the deprecated ones come on top of all");
  }

  @Test
  public void testGetBackendsForNothing() {
    assertTrue(factory.getBackends(null).isEmpty());
    assertTrue(factory.getBackends("").isEmpty());
    assertTrue(factory.getBackends("  ,  ").isEmpty(), "blank names are skipped");
  }

  @Test
  public void testGetBackendsWithUnknownName() {
    expectThrows(BackendException.class, () -> factory.getBackends("H2,nosuchbackend"));
  }


  // ---- the backend info factory --------------------------------------------

  @Test
  public void testBackendInfoFactory() {
    BackendInfoFactory infoFactory = BackendInfoFactory.getInstance();
    assertSame(BackendInfoFactory.getInstance(), infoFactory);

    Backend backend = factory.getBackendByName("H2");
    assertSame(infoFactory.create(backend).getBackend(), backend);
    assertSame(infoFactory.create("H2").getBackend(), backend);

    String url = "jdbc:h2:mem:factorytest";
    BackendInfo info = infoFactory.create(url, "sa", new char[0], new String[] { "public" });
    assertEquals(info.getUrl(), url);
    assertEquals(info.getSchemas(), new String[] { "public" });

    BackendInfo copy = infoFactory.create(info, "other", "pwd".toCharArray());
    assertEquals(copy.getUser(), "other");

    EncryptedProperties props = new EncryptedProperties();
    props.setProperty("url", url);
    assertNotNull(infoFactory.create(props).getBackend());
  }


  private List<String> names(Collection<Backend> backends) {
    return backends.stream().map(Backend::getName).toList();
  }

}

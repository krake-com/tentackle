package org.tentackle.sql.metadata;

import java.util.Locale;

/**
 * Index column metadata for oracle.<br>
 * Resolves the system-generated virtual columns oracle creates for filtered,
 * function-based and descending indexes back to the model's view of the index,
 * i.e. a column name, an optional function name and — for filtered indexes —
 * the filter condition hidden in a {@code CASE WHEN ... THEN ... END} expression.
 *
 * @author harald
 * @see OracleIndexMetaData
 */
public class OracleIndexColumnMetaData extends IndexColumnMetaData {

  /**
   * A parsed index column expression.
   *
   * @param filterCondition the condition of a {@code CASE WHEN}-expression, null if none
   * @param functionName the function name in uppercase, null if none
   * @param columnName the column name in lowercase
   */
  public record ColumnExpression(String filterCondition, String functionName, String columnName) {}


  /** prefix of oracle's system-generated virtual columns. */
  private static final String VIRTUAL_COLUMN_PREFIX = "sys_nc";

  /** suffix of oracle's system-generated virtual columns. */
  private static final String VIRTUAL_COLUMN_SUFFIX = "$";


  /**
   * Parses an index column expression as stored in {@code ALL_IND_EXPRESSIONS}.<br>
   * Understands the {@code CASE WHEN <condition> THEN <expression> END} form
   * created for filtered indexes, the {@code FUNC(<column>)} form of function-based
   * indexes and the plain {@code "COLUMN"} form of descending indexes.
   * Oracle's double quotes are removed from all identifiers.
   *
   * @param expression the expression
   * @return the parsed expression
   */
  public static ColumnExpression parseColumnExpression(String expression) {
    String filterCondition = null;
    String columnExpression = expression.trim();

    if (indexOfKeyword(columnExpression, "CASE", 0) == 0) {
      int whenNdx = indexOfKeyword(columnExpression, "WHEN", 4);
      int thenNdx = whenNdx < 0 ? -1 : indexOfKeyword(columnExpression, "THEN", whenNdx + 4);
      if (thenNdx > 0) {
        // an ELSE-part is never generated by tentackle, but don't choke on it
        int tailNdx = indexOfKeyword(columnExpression, "ELSE", thenNdx + 4);
        if (tailNdx < 0) {
          tailNdx = indexOfKeyword(columnExpression, "END", thenNdx + 4);
        }
        if (tailNdx > 0) {
          filterCondition = removeQuotes(columnExpression.substring(whenNdx + 4, thenNdx));
          columnExpression = columnExpression.substring(thenNdx + 4, tailNdx);
        }
      }
    }

    columnExpression = removeQuotes(columnExpression);

    // check if function-based (same logic as in IndexColumnMetaData)
    String functionName = null;
    int ndx1 = columnExpression.indexOf('(');
    if (ndx1 >= 0) {
      int ndx2 = columnExpression.lastIndexOf(')');
      if (ndx2 > ndx1) {
        String name = columnExpression.substring(0, ndx1).trim();
        columnExpression = columnExpression.substring(ndx1 + 1, ndx2).trim();
        if (!name.isEmpty()) {
          functionName = name.toUpperCase(Locale.ROOT);
        }
      }
    }

    return new ColumnExpression(filterCondition, functionName, columnExpression.trim().toLowerCase(Locale.ROOT));
  }


  private String columnName;      // the resolved column name
  private String functionName;    // the resolved function name, null if none
  private boolean resolved;       // true if expression resolved (or nothing to resolve)


  /**
   * Creates an index column.
   *
   * @param indexMetaData the index this column belongs to
   */
  public OracleIndexColumnMetaData(IndexMetaData indexMetaData) {
    super(indexMetaData);
  }


  @Override
  public void validate() {
    super.validate();

    columnName = super.getColumnName();
    functionName = super.getFunctionName();

    if (isVirtualColumnName(columnName) && getIndexMetaData() instanceof OracleIndexMetaData oracleIndexMetaData) {
      String expression = oracleIndexMetaData.getColumnExpression(getPosition());
      if (expression != null) {
        ColumnExpression columnExpression = parseColumnExpression(expression);
        columnName = columnExpression.columnName();
        functionName = columnExpression.functionName();
        if (columnExpression.filterCondition() != null && oracleIndexMetaData.getFilterCondition() == null) {
          // all columns of a filtered index carry the same condition: the first one wins
          oracleIndexMetaData.setFilterCondition(columnExpression.filterCondition());
        }
      }
    }

    resolved = true;
  }

  @Override
  public String getColumnName() {
    return resolved ? columnName : super.getColumnName();
  }

  @Override
  public String getFunctionName() {
    return resolved ? functionName : super.getFunctionName();
  }


  /**
   * Returns whether given column name refers to a system-generated virtual column.
   *
   * @param columnName the column name in lowercase
   * @return true if virtual column
   */
  private static boolean isVirtualColumnName(String columnName) {
    return columnName != null &&
           columnName.startsWith(VIRTUAL_COLUMN_PREFIX) && columnName.endsWith(VIRTUAL_COLUMN_SUFFIX);
  }

  /**
   * Finds a keyword within an expression.<br>
   * Only whole words outside of string literals and outside of any parenthesis are considered.
   *
   * @param expression the expression
   * @param keyword the keyword in uppercase
   * @param fromIndex the index to start the search at
   * @return the index of the keyword, -1 if not found
   */
  private static int indexOfKeyword(String expression, String keyword, int fromIndex) {
    int depth = 0;
    char quote = 0;
    for (int ndx = fromIndex; ndx <= expression.length() - keyword.length(); ndx++) {
      char c = expression.charAt(ndx);
      if (quote != 0) {
        if (c == quote) {
          quote = 0;
        }
      }
      else if (c == '\'' || c == '"') {
        quote = c;
      }
      else if (c == '(') {
        depth++;
      }
      else if (c == ')') {
        depth--;
      }
      else if (depth == 0 &&
               expression.regionMatches(true, ndx, keyword, 0, keyword.length()) &&
               !isNamePart(expression, ndx - 1) &&
               !isNamePart(expression, ndx + keyword.length())) {
        return ndx;
      }
    }
    return -1;
  }

  /**
   * Returns whether the character at given index is part of an identifier.
   *
   * @param expression the expression
   * @param ndx the character index, may be out of range
   * @return true if part of an identifier
   */
  private static boolean isNamePart(String expression, int ndx) {
    if (ndx < 0 || ndx >= expression.length()) {
      return false;
    }
    char c = expression.charAt(ndx);
    return Character.isLetterOrDigit(c) || c == '_' || c == '$' || c == '#' || c == '"';
  }

  /**
   * Removes oracle's identifier quotes.
   *
   * @param expression the expression
   * @return the unquoted and trimmed expression
   */
  private static String removeQuotes(String expression) {
    return expression.replace("\"", "").trim();
  }

}

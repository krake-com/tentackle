package org.tentackle.maven.plugin.sql;

import org.testng.SkipException;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.DataProvider;
import org.testng.annotations.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import java.net.URL;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertNotNull;
import static org.testng.Assert.assertNull;

/**
 * Tests the plugin descriptor generated from the mojo annotations.
 * <p>
 * Goal names, the aggregator flag and the parameter defaults are the plugin's API: every pom
 * invoking a goal depends on them, and the {@code @Mojo}/{@code @Parameter} annotations are not
 * retained at runtime. They are therefore asserted against {@code META-INF/maven/plugin.xml},
 * which is what maven actually reads.
 * <p>
 * The descriptor is generated in the {@code process-classes} phase, hence it is available to the
 * tests of the very same build.
 */
@SuppressWarnings({ "exports", "missing-explicit-ctor" })
public class PluginDescriptorTest {

  private Map<String, Element> mojos;


  @BeforeClass
  public void setUp() throws Exception {
    URL url = getClass().getResource("/META-INF/maven/plugin.xml");
    if (url == null) {
      throw new SkipException("no plugin descriptor: run the tests as part of the maven build");
    }

    DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
    factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
    Document document = factory.newDocumentBuilder().parse(url.toString());

    List<Element> mojosElement = children(document.getDocumentElement(), "mojos");
    assertEquals(mojosElement.size(), 1, "malformed plugin descriptor");

    mojos = new HashMap<>();
    for (Element mojo : children(mojosElement.get(0), "mojo")) {
      mojos.put(text(mojo, "goal"), mojo);
    }
  }


  /**
   * The goals of this plugin. All six are aggregators - they run once for the whole reactor,
   * hence documented as {@code mvn tentackle-sql:<goal>} rather than bound to a lifecycle phase.
   *
   * @return the goal name and implementation
   */
  @DataProvider(name = "goals")
  public Object[][] goals() {
    return new Object[][] {
      { "create", CreateSqlMojo.class },
      { "migrate", MigrateSqlMojo.class },
      { "validate", ValidateSqlMojo.class },
      { "run", RunSqlMojo.class },
      { "document", DocumentSqlMojo.class },
      { "reveng", RevengMojo.class }
    };
  }

  @Test(dataProvider = "goals")
  public void goalIsDeclaredAsExpected(String goal, Class<?> mojoClass) {
    Element mojo = mojo(goal);

    assertEquals(text(mojo, "implementation"), mojoClass.getName());
    assertEquals(text(mojo, "aggregator"), "true");
  }

  /**
   * None of the goals is bound to a lifecycle phase: they talk to the model and/or a database and
   * are invoked by hand.
   */
  @Test(dataProvider = "goals")
  public void goalIsNotBoundToAPhase(String goal, Class<?> mojoClass) {
    assertNull(text(mojo(goal), "phase"), goal + " is bound to a phase");
  }

  /**
   * Nothing but the goals above (and the generated help goal) is published.
   */
  @Test
  public void publishesExactlyTheDeclaredGoals() {
    List<String> declared = new ArrayList<>(mojos.keySet());
    declared.remove("help");    // generated by the maven-plugin-plugin

    List<String> expected = new ArrayList<>();
    for (Object[] goal : goals()) {
      expected.add((String) goal[0]);
    }

    declared.sort(null);
    expected.sort(null);
    assertEquals(declared, expected);
  }

  /**
   * {@code create} and {@code migrate} share the same defaults for locating the model and writing
   * the generated SQL - operationally important since the wurbelizer, this plugin and downstream
   * projects all agree on {@code target/wurbel/model} and {@code target/sql} without configuring
   * anything.
   */
  @Test
  public void createAndMigrateShareTheSameLocationDefaults() {
    for (String goal : List.of("create", "migrate")) {
      assertEquals(defaultValue(goal, "modelDir"), "${project.build.directory}/wurbel/model", goal);
      assertEquals(defaultValue(goal, "sqlDir"), "${project.build.directory}/sql", goal);
      assertEquals(defaultValue(goal, "checkReservedTables"), "true", goal);
      assertEquals(defaultValue(goal, "generateHeaderComment"), "true", goal);
    }
  }

  @Test
  public void createDefaultsToCreatemodelDotSql() {
    assertEquals(defaultValue("create", "sqlFileName"), "createmodel.sql");
  }

  @Test
  public void migrateDefaultsToMigratemodelDotSql() {
    assertEquals(defaultValue("migrate", "sqlFileName"), "migratemodel.sql");
  }

  /**
   * {@code failOnUnexpectedTables} defaults to false: an unrecognized table is a warning to
   * investigate, not a build breaker, unless explicitly requested.
   */
  @Test
  public void migrateDoesNotFailOnUnexpectedTablesByDefault() {
    assertEquals(defaultValue("migrate", "failOnUnexpectedTables"), "false");
  }

  /**
   * {@code validate} is documented as "same as the {@code validate} flag of {@code migrate}", so
   * that flag itself has no default in the descriptor - {@link ValidateSqlMojo} forces it in code
   * ({@code enableValidation()}), not via the parameter's default value.
   */
  @Test
  public void validateFlagOfMigrateHasNoDeclaredDefault() {
    assertNull(defaultValue("migrate", "validate"));
  }

  /**
   * {@code document} shares {@code modelDir} with {@code create}/{@code migrate}, but writes to its
   * own {@code docDir} rather than {@code sqlDir}.
   */
  @Test
  public void documentDefaultsToModelDocDirectory() {
    assertEquals(defaultValue("document", "modelDir"), "${project.build.directory}/wurbel/model");
    assertEquals(defaultValue("document", "docDir"), "${project.build.directory}/model-doc");
  }

  /**
   * {@code run} needs a script to execute - the one required, goal-specific parameter.
   */
  @Test
  public void runRequiresAScript() {
    assertEquals(required("run", "script"), "true");
  }


  private Element mojo(String goal) {
    Element mojo = mojos.get(goal);
    assertNotNull(mojo, "no such goal: " + goal + ", got " + mojos.keySet());
    return mojo;
  }

  /**
   * Gets the {@code default-value} of a parameter.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return the default value, null if none
   */
  private String defaultValue(String goal, String parameter) {
    List<Element> configurations = children(mojo(goal), "configuration");
    assertEquals(configurations.size(), 1, goal + " has no configuration");
    List<Element> parameters = children(configurations.getFirst(), parameter);
    if (parameters.isEmpty()) {
      // a parameter without a default value (and no property expression) has no <configuration> entry at all
      return null;
    }
    Element element = parameters.getFirst();
    return element.hasAttribute("default-value") ? element.getAttribute("default-value") : null;
  }

  /**
   * Gets whether a parameter is required.
   *
   * @param goal the goal name
   * @param parameter the parameter name
   * @return "true" or "false"
   */
  private String required(String goal, String parameter) {
    return text(requiredParameter(goal, parameter), "required");
  }

  private Element requiredParameter(String goal, String parameter) {
    List<Element> parameters = children(mojo(goal), "parameters");
    assertEquals(parameters.size(), 1, goal + " has no parameters");
    for (Element element : children(parameters.getFirst(), "parameter")) {
      if (parameter.equals(text(element, "name"))) {
        return element;
      }
    }
    throw new IllegalArgumentException(goal + " has no parameter " + parameter);
  }

  private String text(Element parent, String name) {
    List<Element> elements = children(parent, name);
    return elements.isEmpty() ? null : elements.get(0).getTextContent();
  }

  private List<Element> children(Element parent, String name) {
    List<Element> elements = new ArrayList<>();
    NodeList nodes = parent.getChildNodes();
    for (int i = 0; i < nodes.getLength(); i++) {
      Node node = nodes.item(i);
      if (node instanceof Element element && element.getTagName().equals(name)) {
        elements.add(element);
      }
    }
    return elements;
  }

}

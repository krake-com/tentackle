package org.tentackle.buildsupport.codegen;

import freemarker.template.Configuration;
import freemarker.template.TemplateException;

import java.io.IOException;
import java.io.StringWriter;
import java.util.Map;

/**
 * String to be generated by FreeMarker.
 * <p>
 * Renders a named template with a model to a string, e.g. a command line or a script snippet.
 */
public class GeneratedString {

  private final Configuration cfg;
  @SuppressWarnings("rawtypes")
  private final Map model;
  private final String templateName;

  /**
   * Creates a string generator.
   *
   * @param cfg the FreeMarker configuration
   * @param model the FreeMarker model
   * @param templateName the name of the FreeMarker template
   */
  @SuppressWarnings("rawtypes")
  public GeneratedString(Configuration cfg, Map model, String templateName) {
    this.cfg = cfg;
    this.model = model;
    this.templateName = templateName;
  }

  /**
   * Generates the string.
   *
   * @return the generated string
   * @throws IOException if the template could not be loaded
   * @throws TemplateException if processing the template failed
   */
  public String generate() throws IOException, TemplateException {
    StringWriter writer = new StringWriter();
    cfg.getTemplate(templateName).process(model, writer);
    return writer.toString();
  }
}
